/** The texts for a language code of the box ("de", "en", "fr" …; anything else: English). */
export function textsFor(code) {
  const lang = typeof code === 'string' ? code.slice(0, 2).toLowerCase() : 'en'
  return TEXTS[lang] ?? TEXTS.en
}

/** A text with its {name} places filled in. */
export function fill(text, values = {}) {
  return text.replace(/\{(\w+)\}/g, (all, name) => (name in values ? String(values[name]) : all))
}
